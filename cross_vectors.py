    def get_elevation_along_line(self, dtm_layer, line_geometry):
        """
        Extracts elevation values from a raster layer along a given line.

        :param dtm_layer: The raster layer from which elevation will be extracted.
        :type dtm_layer: QgsRasterLayer

        :param line_geometry: Geometry of the line along which elevation will be sampled.
        :type line_geometry: QgsGeometry

        :return: List of elevation values along the line.
        :rtype: list[float]
        """
        # Check if the provided layer is a raster
        if not isinstance(dtm_layer, QgsRasterLayer):
            return []

        # Distance between two points
        distance_interval = 5.0  

        # Get the length of the line
        length = line_geometry.length()

        print(f'length: {length}')
        # List to hold elevation and distance values
        elevations = []
        distances = []


        # Get the raster data provider
        provider = dtm_layer.dataProvider()

        # Sample raster at equally spaced points along the line
        distance = 0
        print(f'distance: {distance}')
        print(f'length: {length}')
        while distance <= length:
            distances.append(distance)  # add this line
            point_on_line = line_geometry.interpolate(distance).asPoint()
            # Identify the raster value at the point
            result = provider.identify(point_on_line, QgsRaster.IdentifyFormatValue).results()
            if result:
                # Assuming band 1 for elevation. Change if your raster has a different band for elevation.
                elevation = result[1]
                elevations.append(elevation)
            distance += distance_interval
    
        return distances, elevations


